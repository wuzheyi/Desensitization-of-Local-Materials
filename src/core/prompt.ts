/**
 * 送给外部 AI 的提示词模板。
 *
 * 工具本身不调用任何模型，用户要自己把脱敏稿粘到别的 AI 里。
 * 但「AI 是否保留占位符」直接决定还原成功率，所以这段约束必须随稿一起复制出去。
 */
export const PROMPT_TEMPLATE = [
  '请对下面这份材料的文字表达做润色，严格遵守以下约束：',
  '1. 所有 〔类型_序号〕 形式的占位符（如 〔机构_1〕、〔金额_2〕）必须原样保留，包括全角方括号；不要翻译、不要改写、不要合并、不要删除、不要补充说明。',
  '2. 不要猜测或补全占位符所指的真实名称。',
  '3. 不要增删或改动数字、金额、比例、日期，不要重算任何合计或比率。',
  '4. 只优化语句通顺度、书面化程度和段落结构，不改变事实与结论。',
  '5. 直接输出润色后的正文，不要附加解释或前后缀。',
  '',
  '---',
  '',
].join('\n');

/**
 * 把用户（可能改过的）提示词与脱敏稿拼成一段可直接粘给 AI 的文本。
 * prompt 参数缺省时用内置模板；界面允许用户在模板基础上增删约束。
 */
export function buildPrompt(masked: string, prompt: string = PROMPT_TEMPLATE): string {
  const head = prompt.trimEnd();
  // 用户可能把末尾的 --- 分隔符删掉，补一个空行保证两段不粘在一起
  return head ? `${head}\n\n${masked}` : masked;
}
